const fetch = require('node-fetch');

/**
 * Sends the onboarding summary as a real email via the Resend API
 * (https://resend.com), replacing the mailto:-only workaround.
 * API key never reaches the browser — proxied server-side, same
 * pattern as deepseek-agent.js and clickup-sync.js.
 */
exports.handler = async (event) => {
    if (event.httpMethod !== 'POST') {
        return { statusCode: 405, body: 'Method Not Allowed' };
    }

    const RESEND_API_KEY = process.env.RESEND_API_KEY;
    const FROM_EMAIL = process.env.RESEND_FROM_EMAIL || 'onboarding@resend.dev';
    const TEAM_EMAIL = process.env.AGENCY_TEAM_EMAIL;

    if (!RESEND_API_KEY) {
        return {
            statusCode: 500,
            body: JSON.stringify({ error: 'RESEND_API_KEY not configured on Netlify' }),
        };
    }

    let payload;
    try {
        payload = JSON.parse(event.body);
    } catch {
        return { statusCode: 400, body: JSON.stringify({ error: 'Invalid JSON body' }) };
    }

    const { summary, recipientType } = payload;
    if (!summary || !summary.clientInfo) {
        return { statusCode: 400, body: JSON.stringify({ error: 'Missing summary in request body' }) };
    }

    const to = recipientType === 'client' ? summary.clientInfo.email : TEAM_EMAIL;
    if (!to) {
        return {
            statusCode: 400,
            body: JSON.stringify({ error: `No recipient email available for recipientType="${recipientType}"` }),
        };
    }

    const riskLines = (summary.identifiedRisks || [])
        .map((r) => `<li><strong>[${r.severity.toUpperCase()}] ${r.category}:</strong> ${r.description}</li>`)
        .join('');

    const html = `
        <h2>Project Discovery Summary: ${summary.clientInfo.company || summary.clientInfo.name}</h2>
        <p><strong>Service:</strong> ${summary.projectInfo.serviceName}</p>
        <p><strong>Scope:</strong> ${summary.projectInfo.scope}</p>
        <p><strong>Timeline:</strong> ${summary.projectInfo.constraints.timeline || 'Not specified'}</p>
        ${riskLines ? `<h3>Identified Risks</h3><ul>${riskLines}</ul>` : ''}
        <h3>Next Steps</h3>
        <ul>${(summary.nextSteps || []).map((s) => `<li>${s}</li>`).join('')}</ul>
        <p style="color:#888;font-size:12px;">Autonomously generated by the AI Onboarding Agent.</p>
    `;

    try {
        const response = await fetch('https://api.resend.com/emails', {
            method: 'POST',
            headers: {
                'Content-Type': 'application/json',
                Authorization: `Bearer ${RESEND_API_KEY}`,
            },
            body: JSON.stringify({
                from: FROM_EMAIL,
                to: [to],
                subject: `Project Discovery Summary: ${summary.clientInfo.company || summary.clientInfo.name} — ${summary.projectInfo.serviceName}`,
                html,
            }),
        });

        const data = await response.json();

        if (!response.ok) {
            return { statusCode: response.status, body: JSON.stringify({ error: data.message || 'Resend API error' }) };
        }

        return { statusCode: 200, body: JSON.stringify({ success: true, id: data.id }) };
    } catch (error) {
        return { statusCode: 500, body: JSON.stringify({ error: error.message }) };
    }
};
